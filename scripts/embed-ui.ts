// Turns the built single-file widget (dist/mcp-app.html) into a TypeScript string, so the server needs no file lookup
// (a serverless function bundle does not reliably contain loose files).
import fs from "node:fs";
import path from "node:path";

const src = path.join(process.cwd(), "dist", "mcp-app.html");
const out = path.join(process.cwd(), "src", "ui-html.generated.ts");
const html = fs.readFileSync(src, "utf-8");
fs.writeFileSync(out, `// GENERATED by scripts/embed-ui.ts from dist/mcp-app.html. Do not edit.\nexport const UI_HTML = ${JSON.stringify(html)};\n`);
console.log(`embedded ${html.length} bytes into src/ui-html.generated.ts`);
